"""Secondary analysis: ordinal decoding (expected grade + thresholds fitted on EyePACS-VALIDATION only) instead of argmax.
The primary protocol of the report stays argmax (declared before training); this variant shows how much of the
QWK is lost by the decoding rule. DDR is never used to fit anything.

Usage: python ordinal_variant.py --npz-dir DIR --val-dir DIR --runs runs.json --manifest manifest.csv --out OUT [--boot 1000]
Needs <val-dir>/<run>_val_logits_best.npy for every run.
"""
import argparse
import json
import os

import numpy as np
import pandas as pd

ap = argparse.ArgumentParser()
ap.add_argument("--npz-dir", required=True)
ap.add_argument("--val-dir", required=True)
ap.add_argument("--runs", required=True)
ap.add_argument("--manifest", required=True)
ap.add_argument("--out", required=True)
ap.add_argument("--boot", type=int, default=1000)
a = ap.parse_args()
os.makedirs(a.out, exist_ok=True)
K = 5
RUNS = json.load(open(a.runs))
yv = pd.read_csv(a.manifest)
yv = yv[(yv.split == "eyepacs_val") & (yv.error.fillna("") == "")].level.astype(int).values


def qwk(y, p):
    O = np.bincount(y * K + p, minlength=K * K).reshape(K, K).astype(float)
    E = np.outer(O.sum(1), O.sum(0)) / O.sum()
    W = (np.arange(K)[:, None] - np.arange(K)[None, :]) ** 2 / (K - 1) ** 2
    return 1 - (W * O).sum() / (W * E).sum()


def exp_grade(l):
    e = np.exp(l - l.max(1, keepdims=True))
    return ((e / e.sum(1, keepdims=True)) * np.arange(K)).sum(1)


def fit_thresholds(score, y):
    t = np.array([0.5, 1.5, 2.5, 3.5], float)
    best = qwk(y, np.digitize(score, t))
    for _ in range(3):
        for i in range(4):
            for c in np.linspace(t[i] - 0.6, t[i] + 0.6, 49):
                tt = t.copy(); tt[i] = c
                if np.all(np.diff(tt) > 0):
                    q = qwk(y, np.digitize(score, tt))
                    if q > best:
                        best, t = q, tt
    return t, best


res, boots = {}, {}
rng = np.random.RandomState(2024)
for m, runs in RUNS.items():
    res[m] = {"thresholds": [], "val_qwk": [], "eyepacs_test": [], "ddr_test": []}
    for j, r in enumerate(runs):
        lv = np.load(os.path.join(a.val_dir, f"{r}_val_logits_best.npy"))
        assert len(lv) == len(yv)
        t, q = fit_thresholds(exp_grade(lv), yv)
        res[m]["thresholds"].append(t.tolist()); res[m]["val_qwk"].append(float(q))
        for sp in ["eyepacs_test", "ddr_test"]:
            z = np.load(os.path.join(a.npz_dir, f"{r}_{sp}.npz"))
            p = np.digitize(exp_grade(z["logits"].astype(np.float64)), t)
            res[m][sp].append(float(qwk(z["y"], p)))
            if j == 0:
                boots[(m, sp)] = (z["y"], p)
# bootstrap CI (seed 0 runs, shared resamples across models)
for sp in ["eyepacs_test", "ddr_test"]:
    N = len(boots[(list(RUNS)[0], sp)][0])
    B = {m: [] for m in RUNS}
    for _ in range(a.boot):
        idx = rng.randint(0, N, N)
        for m in RUNS:
            y, p = boots[(m, sp)]
            B[m].append(qwk(y[idx], p[idx]))
    for m in RUNS:
        res[m][sp + "_ci95_seed0"] = [float(np.percentile(B[m], 2.5)), float(np.percentile(B[m], 97.5))]
json.dump(res, open(os.path.join(a.out, "ordinal_variant.json"), "w"), indent=2)

T = ["% Auto-generated by ordinal_variant.py", "\\begin{tabularx}{\\textwidth}{l c c c c}", "\\toprule",
     "\\textbf{Model} & \\textbf{QWK val (fit)} & \\textbf{QWK EyePACS-test} & \\textbf{QWK DDR-test} & \\textbf{95\\% CI (DDR, seed 0)} \\\\", "\\midrule"]
for m, r in res.items():
    f = lambda v: f"{np.mean(v):.3f}" + (f" $\\pm$ {np.std(v):.3f}" if len(v) > 1 else "")
    ci = r["ddr_test_ci95_seed0"]
    T.append(f"{m} & {f(r['val_qwk'])} & {f(r['eyepacs_test'])} & {f(r['ddr_test'])} & [{ci[0]:.3f}, {ci[1]:.3f}] \\\\")
T += ["\\bottomrule", "\\end{tabularx}"]
open(os.path.join(a.out, "table_ordinal.tex"), "w").write("\n".join(T))
print(json.dumps({m: {k: v for k, v in r.items() if k in ("val_qwk", "eyepacs_test", "ddr_test")} for m, r in res.items()}, indent=1))
