"""Table: 5-epoch runs versus the same runs continued for 3 more epochs (K5), models B1, B2, M1 (seed 0).
Usage: python budget_table.py --five results/main_5ep --cont results/cont_3ep --out results/cont_3ep
Reads results.json and ordinal_variant.json of both folders and writes table_budget.tex + budget.json."""
import argparse
import json
import os

ap = argparse.ArgumentParser()
ap.add_argument("--five", required=True)
ap.add_argument("--cont", required=True)
ap.add_argument("--out", required=True)
a = ap.parse_args()


def load(d):
    r = json.load(open(os.path.join(d, "results.json")))
    o = json.load(open(os.path.join(d, "ordinal_variant.json")))
    return r, o


r5, o5 = load(a.five)
rc, oc = load(a.cont)
models = [m for m in ["B1", "B2", "M1"] if m in rc["models"]]
rows, out = [], {}
for m in models:
    for lab, (r, o) in [("5", (r5, o5)), ("5+3", (rc, oc))]:
        q = r["models"][m]
        e = q["eyepacs_test"]["qwk"]["per_seed"][0]
        d = q["ddr_test"]["qwk"]["per_seed"][0]
        ci = q["ddr_test"]["qwk"]["ci95_seed0"]
        oe, od = o[m]["eyepacs_test"][0], o[m]["ddr_test"][0]
        auc = q["ddr_test"]["auc_ref"]["per_seed"][0]
        out[f"{m}_{lab}"] = dict(eyepacs=e, ddr=d, ddr_ci=ci, ord_eyepacs=oe, ord_ddr=od, auc_ddr=auc)
        rows.append(f"{m} & {lab} & {e:.3f} & {d:.3f} [{ci[0]:.3f}, {ci[1]:.3f}] & {oe:.3f} & {od:.3f} \\\\")
body = []
for i in range(0, len(rows), 2):
    body += rows[i:i + 2] + (["\\midrule"] if i + 2 < len(rows) else [])
T = ["% Auto-generated by budget_table.py", "\\begin{tabularx}{\\textwidth}{l c c c c c}", "\\toprule",
     "\\textbf{Model} & \\textbf{Epochs} & \\textbf{QWK EyePACS-test} & \\textbf{QWK DDR-test [95\\% CI]} & \\textbf{Ordinal EyePACS} & \\textbf{Ordinal DDR} \\\\",
     "\\midrule"] + body + ["\\bottomrule", "\\end{tabularx}"]
os.makedirs(a.out, exist_ok=True)
open(os.path.join(a.out, "table_budget.tex"), "w").write("\n".join(T))
json.dump(out, open(os.path.join(a.out, "budget.json"), "w"), indent=2)
print(json.dumps(out, indent=1))
