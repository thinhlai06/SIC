"""Table: 5-epoch versus 8-epoch runs of M1 and B2 (budget sensitivity check).
Usage: python budget_table.py --five results/main_5ep --eight results/budget_8ep --out results/budget_8ep
Reads results.json and ordinal_variant.json of both folders (seed-0 values) and writes table_budget.tex + budget.json."""
import argparse
import json
import os

ap = argparse.ArgumentParser()
ap.add_argument("--five", required=True)
ap.add_argument("--eight", required=True)
ap.add_argument("--out", required=True)
a = ap.parse_args()


def load(d):
    r = json.load(open(os.path.join(d, "results.json")))
    o = json.load(open(os.path.join(d, "ordinal_variant.json")))
    return r, o


r5, o5 = load(a.five)
r8, o8 = load(a.eight)
rows, out = [], {}
for m in ["B2", "M1"]:
    for ep, (r, o) in [(5, (r5, o5)), (8, (r8, o8))]:
        e = r["models"][m]["eyepacs_test"]["qwk"]["per_seed"][0]
        d = r["models"][m]["ddr_test"]["qwk"]["per_seed"][0]
        ci = r["models"][m]["ddr_test"]["qwk"]["ci95_seed0"]
        ov = o[m]["val_qwk"][0]
        oe = o[m]["eyepacs_test"][0]
        od = o[m]["ddr_test"][0]
        out[f"{m}_{ep}"] = dict(eyepacs=e, ddr=d, ddr_ci=ci, ord_val=ov, ord_eyepacs=oe, ord_ddr=od)
        rows.append(f"{m} & {ep} & {e:.3f} & {d:.3f} [{ci[0]:.3f}, {ci[1]:.3f}] & {oe:.3f} & {od:.3f} \\\\")
T = ["% Auto-generated by budget_table.py", "\\begin{tabularx}{\\textwidth}{l c c c c c}", "\\toprule",
     "\\textbf{Model} & \\textbf{Epochs} & \\textbf{QWK EyePACS-test} & \\textbf{QWK DDR-test [95\\% CI]} & \\textbf{Ordinal EyePACS} & \\textbf{Ordinal DDR} \\\\",
     "\\midrule"] + rows[:2] + ["\\midrule"] + rows[2:] + ["\\bottomrule", "\\end{tabularx}"]
os.makedirs(a.out, exist_ok=True)
open(os.path.join(a.out, "table_budget.tex"), "w").write("\n".join(T))
json.dump(out, open(os.path.join(a.out, "budget.json"), "w"), indent=2)
print(json.dumps(out, indent=1))
