"""Generate a Kaggle script-kernel folder for one training run (1-2 jobs, one per GPU).

Usage:
  python make_run.py --slug sic-dr-bench --title "SIC DR Bench" --jobs jobs.json \
      [--sources thinhlai/sic-dr-package] [--datasets thinhlai/retfound-mae-naturecfp] [--internet] [--public]

The generated script = a header `JOBS = [...]` + train_lib.py, so the kernel is self-contained.
"""
import argparse
import json
import os

ap = argparse.ArgumentParser()
ap.add_argument("--slug", required=True)
ap.add_argument("--title", required=True)
ap.add_argument("--jobs", required=True, help="path to a JSON list of job configs")
ap.add_argument("--sources", nargs="*", default=["thinhlai/sic-dr-package"])
ap.add_argument("--datasets", nargs="*", default=[])
ap.add_argument("--internet", action="store_true")
ap.add_argument("--public", action="store_true")
ap.add_argument("--out", default=None)
a = ap.parse_args()

here = os.path.dirname(os.path.abspath(__file__))
out = a.out or os.path.join(here, "..", "runs", a.slug)
os.makedirs(out, exist_ok=True)
jobs = json.load(open(a.jobs))
assert 1 <= len(jobs) <= 16
lib = open(os.path.join(here, "train_lib.py"), encoding="utf8").read()
open(os.path.join(out, "script.py"), "w", encoding="utf8").write(
    "# generated by make_run.py; do not edit\nimport json as _json\nJOBS = _json.loads(r'''" + json.dumps(jobs, indent=1) + "''')\n\n" + lib)
meta = {
    "id": f"thinhlai/{a.slug}", "title": a.title, "code_file": "script.py", "language": "python",
    "kernel_type": "script", "is_private": "false" if a.public else "true",
    "enable_gpu": "true", "enable_tpu": "false", "enable_internet": "true" if a.internet else "false",
    "dataset_sources": a.datasets, "competition_sources": [], "kernel_sources": a.sources, "model_sources": [],
}
json.dump(meta, open(os.path.join(out, "kernel-metadata.json"), "w"), indent=2)
print("wrote", os.path.abspath(out))
